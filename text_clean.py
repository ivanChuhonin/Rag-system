"""
Очистка текста постов от мусора перед сохранением/переиндексацией.

Что чистим (и почему именно на уровне текста, а не токенизации):
  - разметка ВК вида [https://vk.com/wall-1_2|подпись] и [club123|Название] —
    это внутренняя ссылка ВК на пост/сообщество; оставляем только подпись
    (то, что реально читается), голый id/URL для смысла текста бесполезен;
  - голые URL (https://..., vk.cc/..., t.me/...), которые не попали в
    разметку выше — тоже режем;
  - решётка у хэштегов (#Дюна2 -> Дюна2) — само слово может быть осмысленным
    (название фильма), а вот "#" — просто шум для BM25 и для эмбеддинга.

Стоп-слова сюда сознательно НЕ входят — это разные задачи:
  - для BM25 стоп-слова убираются на этапе токенизации (search.py), потому
    что там мы явно сравниваем отдельные слова, и частые "и/в/на/что" только
    засоряют инвертированный индекс без пользы (IDF их почти обнуляет, но
    незачем и хранить);
  - для эмбеддингов (embed_index.py) стоп-слова НЕ убираются вообще —
    sentence-эмбеддер обучен на связном тексте и использует служебные слова
    как часть контекста; прогон через "мешок значимых слов" ухудшает вектор,
    а не улучшает. Поэтому clean_text() трогает только явный мусор
    (разметку/ссылки), но никогда не выбрасывает обычные слова языка.
"""

from __future__ import annotations

import re

# [что-угодно-без-|-и-]|подпись] — разметка ВК: [URL|текст] или [club123|текст]
_VK_MARKUP_RE = re.compile(r"\[[^\[\]|]+\|([^\[\]]*)\]")
_URL_RE = re.compile(r"(?:https?://|vk\.cc/|t\.me/|www\.)\S+", re.IGNORECASE)
_HASHTAG_RE = re.compile(r"#(\w+)", re.UNICODE)
_MULTI_SPACE_RE = re.compile(r"[ \t]+")
_MULTI_BLANK_LINE_RE = re.compile(r"\n\s*\n\s*\n+")


def clean_text(text: str) -> str:
    if not text:
        return ""
    text = _VK_MARKUP_RE.sub(lambda m: m.group(1), text)
    text = _URL_RE.sub("", text)
    text = _HASHTAG_RE.sub(r"\1", text)
    text = _MULTI_BLANK_LINE_RE.sub("\n\n", text)
    text = _MULTI_SPACE_RE.sub(" ", text)
    return "\n".join(line.strip() for line in text.split("\n")).strip()
